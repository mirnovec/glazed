    /**
     * The closest predicted block of an ore, ignoring every render setting so the caller decides
     * its own limits. Covers unloaded chunks when predict-unloaded is on, since those land in the
     * same result cache. Null when nothing has been simulated yet.
     */
    public BlockPos nearestPrediction(OverworldOre.Type type, int minY, int maxY) {
        Prediction prediction = nearestPredictionInfo(type, minY, maxY);
        return prediction == null ? null : prediction.position();
    }

    /** Discarded blocks are never targets; exposing them caused the n-17.17 regression. */
    public Prediction nearestPredictionInfo(OverworldOre.Type type, int minY, int maxY) {
        if (mc.player == null) return null;

        BlockPos best = null;
        PredictionState bestState = null;
        long bestSource = Long.MIN_VALUE;
        double bestSq = Double.MAX_VALUE;

        ChunkPos centre = mc.player.chunkPosition();
        int range = activeRange();

        for (Map.Entry<Long, List<Vein>> entry : results.entrySet()) {
            // Eviction is periodic; the query itself remains correct in the exact tick an /rtp
            // moves the player or an old chunk packet arrives.
            if (!inRange(entry.getKey(), centre, range)) continue;

            List<Vein> veins = entry.getValue();
            for (Vein vein : veins) {
                if (vein.type() != type) continue;
                if (vein.hiY() < minY || vein.loY() > maxY) continue;

                for (BlockPos pos : vein.blocks()) {
                    if (pos.getY() < minY || pos.getY() > maxY) continue;
                    if (isMined(pos)) continue;

                    double distSq = distanceSqr(pos);
                    if (distSq >= bestSq) continue;

                    bestSq = distSq;
                    best = pos;
                    bestSource = entry.getKey();
                    bestState = rawChunks.contains(entry.getKey())
                        ? PredictionState.GENERATED : PredictionState.VERIFIED;
                }
            }
        }

        return best == null ? null : new Prediction(best, bestState, bestSource);
    }

    /**
     * Looks up one exact prediction without allowing a nearer candidate to steal the target.
     * Em Ore uses this to hold a chosen vein while its chunk changes from seed-only to loaded.
     */
    public Prediction predictionInfoAt(OverworldOre.Type type, BlockPos pos, int minY, int maxY) {
        if (pos == null || pos.getY() < minY || pos.getY() > maxY || isMined(pos)) return null;

        ChunkPos blockChunk = ChunkPos.containing(pos);
        if (!inActiveRange(blockChunk.pack())) return null;

        // results are keyed by the feature's placement/source chunk, not necessarily the chunk
        // containing a block at the edge of its vein. Emerald is tiny, but all vanilla OreFeature
        // veins fit within this 3x3 source neighbourhood.
        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                long sourceKey = ChunkPos.pack(blockChunk.x() + dx, blockChunk.z() + dz);
                List<Vein> veins = results.get(sourceKey);
                if (veins == null) continue;

                for (Vein vein : veins) {
                    if (vein.type() != type || vein.hiY() < minY || vein.loY() > maxY) continue;
                    if (vein.blocks().contains(pos)) {
                        return new Prediction(pos, rawChunks.contains(sourceKey)
                            ? PredictionState.GENERATED : PredictionState.VERIFIED, sourceKey);
                    }
                }
            }
        }

        return null;
    }

    /** True when a cached target still belongs to the square currently being searched. */
    public boolean isWithinPredictionRange(BlockPos pos) {
        return pos != null && mc.player != null
            && inRange(ChunkPos.pack(pos), mc.player.chunkPosition(), activeRange() + 1);
    }

