    private String notReady() {
        if (mc.level == null || mc.player == null) return "Join a server first.";
        if (PlayerUtils.getDimension() != Dimension.Overworld) return "Overworld only.";
        if (oreConfig == null || OverworldOre.all() == null) {
            // a diagnostic that refuses to run until you enable the module is a diagnostic that
            // does not get run, so build the table here instead. Costs about a second, once.
            try {
                oreConfig = OverworldOre.get(mc.level.getMinY(), mc.level.getHeight());
            } catch (Throwable t) {
                return "Could not load ore data: " + t;
            }
        }

        Long parsed = parseSeed();
        if (parsed == null) return "No valid seed set.";
        seed = parsed;

        return null;
    }

    /** What the code actually computed, for eyeballing against the vanilla data. */
    public String table() {
        String bad = notReady();
        if (bad != null) return bad;

        StringBuilder out = new StringBuilder();
        out.append("seed=").append(seed)
            .append("  step=").append(OverworldOre.all().get(0).step)
            .append("  minY=").append(mc.level.getMinY())
            .append("  height=").append(mc.level.getHeight()).append("\n");

        for (OverworldOre ore : OverworldOre.all()) {
            out.append(String.format("%-22s type=%-9s index=%-3d size=%-3d discardAir=%.1f rarity=%-2d scattered=%-5b targets=%s%n",
                ore.name, ore.type, ore.index, ore.size, ore.discardOnAirChance, ore.rarity, ore.scattered, ore.resultBlocks));
        }

        return write("ore_table.txt", out.toString(),
            OverworldOre.all().size() + " placements at step " + OverworldOre.all().get(0).step);
    }

    /**
     * Ground truth without mining anything.
     *
     * Anti-xray hides buried ore but leaves granite, diorite, andesite, tuff, dirt, gravel and
     * clay alone, and those come out of the same pipeline with the same population seed. If the
     * seed and the feature indices are right, the predictions for those have to land on blocks
     * that are already in the client world. Compared against what pure chance would give, which
     * is what makes the number mean anything.
     *
     * The real ores are reported the same way. They only have visible blocks where a cave has
     * exposed them, so a low count there is not a failure: read the geology rows for the verdict
     * on the seed, then the ore rows for whether that ore is following the same seed.
     */
    public String verifyAgainstVisibleOre() {
        return verifyAgainstVisibleOre(false);
    }

    public String verifyAgainstVisibleOre(boolean everything) {
        String bad = notReady();
        if (bad != null) return bad;

        ChunkPos centre = mc.player.chunkPosition();

        // the geology features are the whole point of this measurement, and simulating the ores
        // you are not looking at costs far more than they do. .ore verify all overrides it.
        List<OverworldOre> ores = new ArrayList<>();
        for (OverworldOre ore : OverworldOre.all()) {
            if (everything || !ore.type.hidden || enabled(ore.type) || hasAirDiscard(ore)) ores.add(ore);
        }

        // the modes only differ where an air-exposure discard burns a random float, so there is
        // nothing to compare unless one of the selected ores has one
        boolean compareModes = false;
        for (OverworldOre ore : ores) if (hasAirDiscard(ore)) compareModes = true;

        Map<RngMode, Map<OverworldOre, Set<Long>>> byMode = new EnumMap<>(RngMode.class);
        byMode.put(RngMode.AlwaysStone, simulateRaw(centre, VERIFY_RADIUS, ores, RngMode.AlwaysStone));

        // A wrong seed is not the same as random noise. Granite only generates between y 0 and
        // 60, so predictions and real blocks pile into the same narrow band whatever the seed is,
        // and comparing against a flat chance-per-block baseline made that look like a signal.
        // Simulating a decoy seed keeps the shape and the height band and destroys only the
        // alignment, which is the thing being tested.
        long realSeed = seed;
        Map<OverworldOre, Set<Long>> decoy;
        try {
            seed = realSeed ^ 0x9E3779B97F4A7C15L;
            decoy = simulateRaw(centre, VERIFY_RADIUS, ores, RngMode.AlwaysStone);
        } finally {
            seed = realSeed;
        }

        if (compareModes) {
            byMode.put(RngMode.World, simulateRaw(centre, VERIFY_RADIUS, ores, RngMode.World));
            byMode.put(RngMode.AirAsStone, simulateRaw(centre, VERIFY_RADIUS, ores, RngMode.AirAsStone));
        }

        Map<OverworldOre, Set<Long>> predicted = byMode.get(RngMode.AlwaysStone);

        Set<Block> wanted = new HashSet<>();
        for (OverworldOre ore : ores) wanted.addAll(ore.resultBlocks);

        Map<Block, Set<Long>> real = new HashMap<>();
        long volume = 0;
        int chunks = 0;

        BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();

        for (int cx = centre.x() - VERIFY_RADIUS; cx <= centre.x() + VERIFY_RADIUS; cx++) {
            for (int cz = centre.z() - VERIFY_RADIUS; cz <= centre.z() + VERIFY_RADIUS; cz++) {
                if (mc.level.getChunk(cx, cz, ChunkStatus.FULL, false) == null) continue;
                chunks++;

                for (int dx = 0; dx < 16; dx++) {
                    for (int dz = 0; dz < 16; dz++) {
                        for (int y = VERIFY_MIN_Y; y <= VERIFY_MAX_Y; y++) {
                            volume++;
                            pos.set((cx << 4) + dx, y, (cz << 4) + dz);
                            BlockState state = mc.level.getBlockState(pos);
                            Block block = state.getBlock();
                            if (!wanted.contains(block)) continue;

                            real.computeIfAbsent(block, k -> new HashSet<>()).add(pos.asLong());
                        }
                    }
                }
            }
        }

        if (chunks == 0) return "No chunks loaded.";

        StringBuilder out = new StringBuilder();
        out.append("seed=").append(seed)
            .append("  region=").append(activeRegion().label)
            .append(seedIsPerRegion() ? " (per region)" : " (fallback)")
            .append("  chunks=").append(chunks)
            .append("  y=").append(VERIFY_MIN_Y).append("..").append(VERIFY_MAX_Y)
            .append("  volume=").append(volume).append("\n");

        SeedWorld terrainWorld = seedWorld;
        out.append("deep emerald terrain: accepted=").append(terrainAccepted)
            .append(" rejected=").append(terrainRejected)
            .append(" cachedChunks=").append(terrainWorld == null ? 0 : terrainWorld.terrainChunks())
            .append(" pendingChunks=").append(terrainWorld == null ? 0 : terrainWorld.terrainPending())
            .append(" failure=").append(terrainWorld == null || terrainWorld.terrainFailure() == null
                ? "none" : terrainWorld.terrainFailure())
            .append("\n\n");

        out.append("per feature (precision: of the blocks this feature predicts, how many are really there)\n");
        out.append(String.format("%-22s %-5s %-10s %-8s %-8s%n", "feature", "idx", "predicted", "onReal", "precision"));

        Map<OverworldOre.Type, Set<Long>> predictedByType = new EnumMap<>(OverworldOre.Type.class);

        for (OverworldOre ore : ores) {
            Set<Long> inWindow = window(predicted.get(ore));
            predictedByType.computeIfAbsent(ore.type, k -> new HashSet<>()).addAll(inWindow);

            int hits = 0;
            for (long p : inWindow) if (isReal(real, ore.resultBlocks, p)) hits++;

            out.append(String.format("%-22s %-5d %-10d %-8d %.1f%%%n",
                ore.name, ore.index, inWindow.size(), hits,
                inWindow.isEmpty() ? 0.0 : 100.0 * hits / inWindow.size()));
        }

        out.append("\nper ore (recall: of the blocks really there, how many were predicted)\n");
        out.append("decoy is the same simulation on a deliberately wrong seed: real must beat it\n");
        out.append(String.format("%-10s %-6s %-10s %-8s %-9s %-9s %s%n",
            "ore", "role", "realBlocks", "matched", "recall", "decoy", "verdict"));

        int geologyChecked = 0, geologyGood = 0;
        StringBuilder chat = new StringBuilder();

        for (OverworldOre.Type type : OverworldOre.Type.values()) {
            Set<Long> pred = predictedByType.getOrDefault(type, Set.of());

            Set<Long> realOfType = new HashSet<>();
            for (OverworldOre ore : ores) {
                if (ore.type != type) continue;
                for (Block block : ore.resultBlocks) realOfType.addAll(real.getOrDefault(block, Set.of()));
            }

            int matched = 0;
            for (long p : realOfType) if (pred.contains(p)) matched++;

            Set<Long> decoyPred = new HashSet<>();
            for (OverworldOre ore : ores) {
                if (ore.type == type) decoyPred.addAll(window(decoy.get(ore)));
            }

            int decoyMatched = 0;
            for (long p : realOfType) if (decoyPred.contains(p)) decoyMatched++;

            double recall = realOfType.isEmpty() ? 0 : 100.0 * matched / realOfType.size();
            double decoyRecall = realOfType.isEmpty() ? 0 : 100.0 * decoyMatched / realOfType.size();

            boolean good = recall >= 40 && recall > 4 * Math.max(decoyRecall, 0.5);

            String verdict;
            if (realOfType.size() < 20) verdict = "too few blocks";
            else if (good) verdict = "MATCHES SEED";
            else verdict = "DOES NOT MATCH";

            String role = type.hidden ? "hidden" : (type.reference ? "REFERENCE" : "noisy");

            // only the clean references decide the verdict: dirt, gravel and clay are mostly
            // surface generation these features never touched
            if (type.reference && realOfType.size() >= 20) {
                geologyChecked++;
                if (good) geologyGood++;
            }

            out.append(String.format("%-10s %-6s %-10d %-8d %-9.1f %-9.1f %s%n",
                type, role, realOfType.size(), matched, recall, decoyRecall, verdict));

            if (realOfType.size() >= 20 && (type.reference || type.hidden)) {
                chat.append(String.format("%s %.0f%% (decoy %.0f%%)  ",
                    type.name().toLowerCase(Locale.ROOT), recall, decoyRecall));
            }
        }

        if (compareModes) {
            out.append("\nair-discard ores by rng-mode (recall, higher is better)\n");
            out.append(String.format("%-10s %-12s %-12s %-12s%n", "ore", "World", "AirAsStone", "AlwaysStone"));

            for (OverworldOre.Type type : OverworldOre.Type.values()) {
                boolean relevant = false;
                for (OverworldOre ore : ores) if (ore.type == type && hasAirDiscard(ore)) relevant = true;
                if (!relevant) continue;

                Set<Long> realOfType = realOfType(real, ores, type);
                if (realOfType.size() < 20) {
                    out.append(String.format("%-10s only %d real blocks nearby, cannot tell%n", type, realOfType.size()));
                    continue;
                }

                out.append(String.format("%-10s %-12.1f %-12.1f %-12.1f%n", type,
                    modeRecall(byMode.get(RngMode.World), ores, type, realOfType),
                    modeRecall(byMode.get(RngMode.AirAsStone), ores, type, realOfType),
                    modeRecall(byMode.get(RngMode.AlwaysStone), ores, type, realOfType)));
            }
        }

        String headline;
        if (geologyChecked == 0) {
            headline = "no granite/diorite/andesite/tuff nearby, move somewhere with more untouched stone";
        } else if (geologyGood == geologyChecked) {
            headline = "SEED IS CORRECT FOR " + activeRegion().label.toUpperCase(Locale.ROOT) + " (" + geologyGood + "/" + geologyChecked + " references match)";
        } else if (geologyGood == 0) {
            headline = "SEED IS WRONG FOR " + activeRegion().label.toUpperCase(Locale.ROOT) + " (0/" + geologyChecked + " references match)";
        } else {
            headline = "MIXED: " + geologyGood + "/" + geologyChecked + " references match, look at the file";
        }

        out.append("\n").append(headline).append("\n");

        // the per ore rows go to chat too, otherwise the verdict is a number with no working out
        StringBuilder report = new StringBuilder(headline);
        report.append("\n").append(chat.length() == 0 ? "no ore or geology blocks found nearby" : chat.toString().trim());

        // every run also gets appended, because a region sweep overwrote itself otherwise and
        // there was no way to tell afterwards which region a result came from
        append("ore_verify_log.txt", String.format(
            "=== region=%s seed=%d at %d %d %d ===%n%s%n",
            activeRegion().label, seed,
            mc.player.getBlockX(), mc.player.getBlockY(), mc.player.getBlockZ(),
            out));

        return write("ore_verify.txt", out.toString(), report.toString());
    }

    private boolean hasAirDiscard(OverworldOre ore) {
        return ore.discardOnAirChance > 0f && ore.discardOnAirChance < 1f;
    }

    private Set<Long> realOfType(Map<Block, Set<Long>> real, List<OverworldOre> ores, OverworldOre.Type type) {
        Set<Long> out = new HashSet<>();

        for (OverworldOre ore : ores) {
            if (ore.type != type) continue;
            for (Block block : ore.resultBlocks) out.addAll(real.getOrDefault(block, Set.of()));
        }

        return out;
    }

    private double modeRecall(Map<OverworldOre, Set<Long>> predicted, List<OverworldOre> ores, OverworldOre.Type type, Set<Long> realOfType) {
        if (predicted == null || realOfType.isEmpty()) return 0;

        Set<Long> pred = new HashSet<>();
        for (OverworldOre ore : ores) {
            if (ore.type == type) pred.addAll(window(predicted.get(ore)));
        }

        int matched = 0;
        for (long p : realOfType) if (pred.contains(p)) matched++;

        return 100.0 * matched / realOfType.size();
    }

    private Set<Long> window(Set<Long> positions) {
        if (positions == null) return Set.of();

        Set<Long> out = new HashSet<>();
        for (long p : positions) {
            int y = BlockPos.getY(p);
            if (y >= VERIFY_MIN_Y && y <= VERIFY_MAX_Y) out.add(p);
        }

        return out;
    }

    private boolean isReal(Map<Block, Set<Long>> real, List<Block> blocks, long pos) {
        for (Block block : blocks) {
            Set<Long> set = real.get(block);
            if (set != null && set.contains(pos)) return true;
        }

        return false;
    }

    /**
     * Brute forces the feature index for every placement that has enough real blocks nearby, by
     * trying each index and measuring how well the predictions line up. If these come back at
     * their vanilla indices the server ordering is vanilla; if they are shifted, the same shift
     * is what would be breaking the ores you cannot see.
     *
     * Rows are labelled by feature name, not ore type, because two variants of one ore have
     * different indices and only one of them may generate at the height you are standing at.
     */
    public String scanIndices() {
        String bad = notReady();
        if (bad != null) return bad;

        ChunkPos centre = mc.player.chunkPosition();
        StringBuilder out = new StringBuilder();
        out.append("seed=").append(seed).append("  radius=").append(SCAN_RADIUS).append(" chunks\n");
        out.append(String.format("%-22s %-9s %-8s %-9s %-8s %-10s %s%n",
            "feature", "vanilla", "hits", "bestIndex", "hits", "realBlocks", ""));

        int shifted = 0, ok = 0;

        for (OverworldOre ore : OverworldOre.all()) {
            if (ore.heightProvider == null) continue;

            Set<Long> actual = new HashSet<>();
            BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();

            for (int cx = centre.x() - SCAN_RADIUS; cx <= centre.x() + SCAN_RADIUS; cx++) {
                for (int cz = centre.z() - SCAN_RADIUS; cz <= centre.z() + SCAN_RADIUS; cz++) {
                    if (mc.level.getChunk(cx, cz, ChunkStatus.FULL, false) == null) continue;

                    for (int dx = 0; dx < 16; dx++) {
                        for (int dz = 0; dz < 16; dz++) {
                            for (int y = VERIFY_MIN_Y; y <= VERIFY_MAX_Y; y++) {
                                pos.set((cx << 4) + dx, y, (cz << 4) + dz);
                                BlockState state = mc.level.getBlockState(pos);

                                for (Block block : ore.resultBlocks) {
                                    if (state.is(block)) { actual.add(pos.asLong()); break; }
                                }
                            }
                        }
                    }
                }
            }

            if (actual.size() < 20) {
                out.append(String.format("%-22s %-9d %-8s %-9s %-8s %-10d skipped, not enough real blocks%n",
                    ore.name, ore.index, "-", "-", "-", actual.size()));
                continue;
            }

            int bestIndex = -1, bestHits = -1, vanillaHits = 0;

            boolean savedRawPass = rawPass;
            rawPass = false;
            forceRaw = true;
            try {
                for (int idx = 0; idx <= 40; idx++) {
                    int hits = countHits(centre, SCAN_RADIUS, ore, idx, actual);
                    if (idx == ore.index) vanillaHits = hits;
                    if (hits > bestHits) { bestHits = hits; bestIndex = idx; }
                }
            } finally {
                forceRaw = false;
                rawPass = savedRawPass;
            }

            boolean matches = bestIndex == ore.index;
            if (matches) ok++; else shifted++;

            out.append(String.format("%-22s %-9d %-8d %-9d %-8d %-10d %s%n",
                ore.name, ore.index, vanillaHits, bestIndex, bestHits, actual.size(),
                matches ? "OK" : "<-- SHIFTED"));
        }

        String headline = String.format("index scan: %d at their vanilla index, %d shifted", ok, shifted);
        out.append("\n").append(headline).append("\n");

        return write("ore_index_scan.txt", out.toString(), headline);
    }

    private int countHits(ChunkPos centre, int radius, OverworldOre ore, int index, Set<Long> actual) {
        int hits = 0;

        for (int cx = centre.x() - radius; cx <= centre.x() + radius; cx++) {
            for (int cz = centre.z() - radius; cz <= centre.z() + radius; cz++) {
                ChunkPos pos = new ChunkPos(cx, cz);
                if (mc.level.getChunk(cx, cz, ChunkStatus.FULL, false) == null || !neighboursLoaded(pos)) continue;

                int minX = cx << 4, minZ = cz << 4;

                WorldgenRandom random = new WorldgenRandom(WorldgenRandom.Algorithm.XOROSHIRO.newInstance(0));
                long populationSeed = random.setDecorationSeed(seed, minX, minZ);
                random.setFeatureSeed(populationSeed, index, ore.step);

                int repeat = ore.count.sample(random);

                for (int i = 0; i < repeat; i++) {
                    if (ore.rarity != 1 && random.nextFloat() >= 1.0f / ore.rarity) continue;

                    int x = random.nextInt(16) + minX;
                    int z = random.nextInt(16) + minZ;
                    int y = ore.heightProvider.sample(random, ore.heightContext);
                    BlockPos origin = new BlockPos(x, y, z);

                    if (!biomeHas(origin, ore)) continue;

                    discardBuffer.clear();

                    List<BlockPos> blocks = ore.scattered
                        ? generateScattered(random, origin, ore)
                        : generateNormal(random, origin, ore);

                    for (BlockPos b : blocks) if (actual.contains(b.asLong())) hits++;
                }
            }
        }

        return hits;
    }

    /** Pure geometry over a square of chunks: seed and biome only, no world filtering. */
    private Map<OverworldOre, Set<Long>> simulateRaw(ChunkPos centre, int radius, List<OverworldOre> ores, RngMode mode) {
        Map<OverworldOre, Set<Long>> out = new LinkedHashMap<>();
        for (OverworldOre ore : ores) out.put(ore, new HashSet<>());

        // A diagnostic must never inherit a half-finished production pass. TerrainPending used to
        // leak out of /ore verify when rawPass was observed here, even though forceRaw is meant to
        // be pure loaded-world geometry. Pin the diagnostic mode explicitly and restore it after.
        boolean savedRawPass = rawPass;
        rawPass = false;
        forceRaw = true;
        rngOverride = mode;
        try {
            for (int cx = centre.x() - radius; cx <= centre.x() + radius; cx++) {
                for (int cz = centre.z() - radius; cz <= centre.z() + radius; cz++) {
                    ChunkPos pos = new ChunkPos(cx, cz);
                    if (mc.level.getChunk(cx, cz, ChunkStatus.FULL, false) == null || !neighboursLoaded(pos)) continue;

                    int minX = cx << 4, minZ = cz << 4;

                    WorldgenRandom random = new WorldgenRandom(WorldgenRandom.Algorithm.XOROSHIRO.newInstance(0));
                    long populationSeed = random.setDecorationSeed(seed, minX, minZ);

                    for (OverworldOre ore : ores) {
                        if (ore.heightProvider == null) continue;

                        random.setFeatureSeed(populationSeed, ore.index, ore.step);

                        int repeat = ore.count.sample(random);

                        for (int i = 0; i < repeat; i++) {
                            if (ore.rarity != 1 && random.nextFloat() >= 1.0f / ore.rarity) continue;

                            int x = random.nextInt(16) + minX;
                            int z = random.nextInt(16) + minZ;
                            int y = ore.heightProvider.sample(random, ore.heightContext);
                            BlockPos origin = new BlockPos(x, y, z);

                            if (!biomeHas(origin, ore)) continue;

                            discardBuffer.clear();

                            List<BlockPos> blocks = ore.scattered
                                ? generateScattered(random, origin, ore)
                                : generateNormal(random, origin, ore);

                            Set<Long> set = out.get(ore);
                            for (BlockPos b : blocks) set.add(b.asLong());
                        }
                    }
                }
            }
        } finally {
            forceRaw = false;
            rngOverride = null;
            rawPass = savedRawPass;
        }

        return out;
    }

    /**
     * Anti-xray hides buried ore but reports anything a cave has exposed, so every real block of
     * an enabled ore gets recorded here. Three positions in three different chunks are enough to
     * solve for a per-feature seed if the server has set one.
     */
    private void scanForRealOre() {
        if (mc.player == null || mc.level == null || activeOres == null) return;

        Set<Block> wanted = new HashSet<>();
        for (OverworldOre ore : activeOres) {
            if (ore.type.hidden) wanted.addAll(ore.resultBlocks);
        }

        if (wanted.isEmpty()) return;

        ChunkPos centre = mc.player.chunkPosition();
        int playerY = mc.player.getBlockY();
        int lo = Math.max(mc.level.getMinY(), playerY - 48);
        int hi = Math.min(mc.level.getMaxY(), playerY + 48);

        StringBuilder found = new StringBuilder();
        BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();

        for (int dx = 0; dx < 16; dx++) {
            for (int dz = 0; dz < 16; dz++) {
                for (int y = lo; y <= hi; y++) {
                    pos.set(centre.getMinBlockX() + dx, y, centre.getMinBlockZ() + dz);
                    BlockState state = mc.level.getBlockState(pos);
                    if (!wanted.contains(state.getBlock())) continue;

                    if (!loggedOre.add(pos.asLong())) continue;

                    found.append(pos.getX()).append(" ").append(pos.getY()).append(" ").append(pos.getZ())
                         .append(" ").append(state.getBlock().getName().getString()).append("\n");
                }
            }
        }

        if (found.length() == 0) return;

        Path file = mc.gameDirectory.toPath().resolve("glazed").resolve("found_overworld_ore.txt");
        try {
            Files.createDirectories(file.getParent());
            Files.writeString(file, found.toString(), StandardCharsets.UTF_8,
                java.nio.file.StandardOpenOption.CREATE, java.nio.file.StandardOpenOption.APPEND);
            info("Logged real ore (%d total).", loggedOre.size());
        } catch (IOException ignored) {
            // not worth interrupting mining over
        }
    }

    /**
     * The summary is plain text, never a format string. It carries percent signs from the
     * measurement, and running it through String.format threw and swallowed the whole result.
     */
    private void append(String fileName, String body) {
        Path file = mc.gameDirectory.toPath().resolve("glazed").resolve(fileName);

        try {
            Files.createDirectories(file.getParent());
            Files.writeString(file, body, StandardCharsets.UTF_8,
                java.nio.file.StandardOpenOption.CREATE, java.nio.file.StandardOpenOption.APPEND);
        } catch (IOException ignored) {
            // the run still returns its result, the log is a convenience
        }
    }

    private String write(String fileName, String body, String summary) {
        Path file = mc.gameDirectory.toPath().resolve("glazed").resolve(fileName);

        try {
            Files.createDirectories(file.getParent());
            Files.writeString(file, body, StandardCharsets.UTF_8);
        } catch (IOException e) {
            return summary + " (could not write " + fileName + ": " + e.getMessage() + ")";
        }

        return summary + " -> " + file;
    }
