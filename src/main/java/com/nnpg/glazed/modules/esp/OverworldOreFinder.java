    @EventHandler
    private void onTick(TickEvent.Post event) {
        if (mc.level == null || mc.player == null || oreConfig == null) return;
        if (PlayerUtils.getDimension() != Dimension.Overworld) return;

        if (activeOres == null) {
            rebuildActive();
            info("Ore data ready, %d of %d placements enabled.", activeOres.size(), OverworldOre.all().size());
        }

        // /rtp to another region puts you in a different world, so everything computed for the
        // old one is wrong and has to go
        DonutRegion region = activeRegion();
        if (region != lastRegion) {
            lastRegion = region;
            predictionEpoch++;
            mined.clear();
            reload();

            if (seedIsPerRegion()) info("Region is now %s, using its seed.", region.label);
            else warning("Region is now %s and has no seed. Falling back to the seed setting, which is probably a different world.", region.label);
        }

        ensureSeedWorld();

        // an /rtp moves you thousands of blocks: every cached chunk and every chunk still queued
        // belongs to where you were, and recomputing them wastes the whole per-tick budget
        ChunkPos centre = mc.player.chunkPosition();
        int jump = lastCentre == null ? 0
            : Math.max(Math.abs(centre.x() - lastCentre.x()), Math.abs(centre.z() - lastCentre.z()));

        if (lastCentre != null && jump > Math.max(chunkRange.get(), unloadedRange.get()) + 8) {
            clearResults();
            pendingRescan = true;
        }

        lastCentre = centre;

        if (pendingRescan) {
            pendingRescan = false;
            clearResults();

            // Put the current centre first. Loaded chunks are still verified by compute(), but
            // they must not sit in front of the seed-only search after an /rtp.
            if (predictUnloaded.get() && seedWorld != null) enqueueUnloadedRadius();
            for (ChunkAccess chunk : Utils.chunks(false)) enqueue(chunk.getPos().pack());
        }

        // Terrain generation finishes on its own worker. Only the render thread may touch the
        // module's work queues or client world, so completed placement chunks re-enter here.
        for (Long key; (key = terrainReady.poll()) != null; ) enqueueFirst(key);

        // chunks skipped because their neighbours had not arrived yet get another go here
        if (++tickCounter >= 40) {
            tickCounter = 0;
            floorCache.clear();

            if (logRealOre.get()) scanForRealOre();

            evictDistant();
            if (predictUnloaded.get() && seedWorld != null) enqueueUnloadedRadius();

            for (ChunkAccess chunk : Utils.chunks(false)) {
                long key = chunk.getPos().pack();
                if (!results.containsKey(key)) enqueue(key);
            }
        }

        // a full radius rescan is millions of block lookups, so it is spread over ticks
        int budget = chunksPerTick.get();
        while (budget-- > 0 && !ready.isEmpty()) {
            SeedWorld world = seedWorld;
            if (world != null && world.terrainPending() >= MAX_TERRAIN_PENDING) break;
            long key = ready.poll();
            queue.remove(key);
            compute(ChunkPos.unpack(key));
        }
    }

    private void enqueue(long key) {
        if (mc.player == null || !inActiveRange(key)) return;
        if (results.containsKey(key) || !queue.add(key)) return;
        ready.add(key);
    }

    /** Completed dependency retries outrank untouched radius work, preventing terrain LRU churn. */
    private void enqueueFirst(long key) {
        if (mc.player == null || !inActiveRange(key)) return;
        if (results.containsKey(key) || !queue.add(key)) return;
        ready.addFirst(key);
    }

    /**
     * Every chunk in range, whether the client has it or not. Rings keep the closest unfinished
     * work at the front, so an /rtp starts producing useful nearby answers immediately instead of
     * walking from one corner of the square to the other.
     */
    private void enqueueUnloadedRadius() {
        ChunkPos centre = mc.player.chunkPosition();
        int range = unloadedRange.get();

        enqueue(centre.pack());

        for (int radius = 1; radius <= range; radius++) {
            int minX = centre.x() - radius;
            int maxX = centre.x() + radius;
            int minZ = centre.z() - radius;
            int maxZ = centre.z() + radius;

            for (int cx = minX; cx <= maxX; cx++) {
                enqueue(ChunkPos.pack(cx, minZ));
                enqueue(ChunkPos.pack(cx, maxZ));
            }

            for (int cz = minZ + 1; cz < maxZ; cz++) {
                enqueue(ChunkPos.pack(minX, cz));
                enqueue(ChunkPos.pack(maxX, cz));
            }
        }
    }

    /** Every cache and work queue is bounded explicitly; the client's chunk cache can lag an RTP. */
    private void evictDistant() {
        ChunkPos centre = mc.player.chunkPosition();
        int keep = activeRange();

        results.keySet().removeIf(key -> !inRange(key, centre, keep));
        rawChunks.removeIf(key -> !inRange(key, centre, keep));

        // work queued from where you used to be would be computed, land in the cache as the only
        // thing anywhere near a match, and get evicted again on the next sweep, forever
        queue.removeIf(key -> !inRange(key, centre, keep));
        ready.removeIf(key -> !inRange(key, centre, keep));
        terrainWaiting.removeIf(key -> !inRange(key, centre, keep));
        terrainReady.removeIf(key -> !inRange(key, centre, keep));
        preEmeraldMasks.keySet().removeIf(key -> !inRange(key, centre, keep));
    }

    private boolean inRange(long key, ChunkPos centre, int keep) {
        ChunkPos pos = ChunkPos.unpack(key);
        return Math.max(Math.abs(pos.x() - centre.x()), Math.abs(pos.z() - centre.z())) <= keep;
    }

    private int activeRange() {
        return predictUnloaded.get()
            ? Math.max(chunkRange.get(), unloadedRange.get())
            : chunkRange.get();
    }

    private boolean inActiveRange(long key) {
        return mc.player != null && inRange(key, mc.player.chunkPosition(), activeRange());
    }

    @EventHandler
    private void onChunkData(ChunkDataEvent event) {
        if (oreConfig == null) return;

        long key = event.chunk().getPos().pack();

        // Packets already in flight when /rtp completes can arrive after the new sweep starts.
        // Never let one resurrect work from the previous location.
        if (!inActiveRange(key)) {
            results.remove(key);
            rawChunks.remove(key);
            queue.remove(key);
            ready.remove(key);
            return;
        }

        // Seed-backed emeralds are authoritative here. Donut deliberately sends hidden ore as
        // deepslate or air, so replacing this result with a client-world pass destroys good
        // predictions. Keep the original result atomically for its whole in-range lifetime.
        if (rawChunks.contains(key) && results.containsKey(key)) return;

        enqueue(key);
    }

    @EventHandler
    private void onBlockUpdate(BlockUpdateEvent event) {
        if (airCheck.get() != AirCheck.Recheck || !event.newState.isAir()) return;

        // AIR is one of Donut's anti-xray disguises for every hidden ore. It is therefore not
        // evidence that an emerald was mined or that the prediction was wrong. Non-hidden geology
        // can still be rechecked. Veins are keyed by their placement chunk, and may cross into a
        // neighbouring block chunk, so inspect every possible source chunk rather than only the
        // block's own chunk.
        ChunkPos blockChunk = ChunkPos.containing(event.pos);
        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                List<Vein> veins = results.get(ChunkPos.pack(blockChunk.x() + dx, blockChunk.z() + dz));
                if (veins == null) continue;

                for (Vein vein : veins) {
                    if (!vein.type().hidden) vein.blocks().remove(event.pos);
                }
            }
        }
    }

    /**
     * You mined it yourself. The client decides this locally, before any server reply, so it is
     * the one signal about a hidden ore that anti-xray has no say in.
     */
    @EventHandler
    private void onBreakBlock(BreakBlockEvent event) {
        forget(event.blockPos);
    }

    /**
     * Someone else mined it. Vanilla fires the block-destroy level event for every player break
     * and excludes the breaker, so this covers exactly the other half of {@link #onBreakBlock}.
     *
     * This is still not a block-state check: the server is reporting that a player broke
     * something, not what is in the block, and a disguised ore produces the same event as a real
     * one. Nothing here can be used to make a real emerald disappear from the render.
     */
    @EventHandler
    private void onPacketReceive(PacketEvent.Receive event) {
        if (!(event.packet instanceof ClientboundLevelEventPacket packet)) return;
        if (packet.getType() != LevelEvent.PARTICLES_DESTROY_BLOCK) return;

        forget(packet.getPos());
    }

    /**
     * Only positions this module actually draws are remembered, so a stripmining session cannot
     * grow the set past the handful of ore blocks it predicted.
     */
    private void forget(BlockPos pos) {
        if (!forgetMined.get() || pos == null || !isPredicted(pos)) return;

        mined.add(pos.asLong());
    }

    /** Veins are keyed by placement chunk and can cross its edge, so check the 3x3 around it. */
    private boolean isPredicted(BlockPos pos) {
        ChunkPos blockChunk = ChunkPos.containing(pos);

        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                List<Vein> veins = results.get(ChunkPos.pack(blockChunk.x() + dx, blockChunk.z() + dz));
                if (veins == null) continue;

                for (Vein vein : veins) {
                    if (vein.blocks().contains(pos) || vein.discarded().contains(pos)) return true;
                }
            }
        }

        return false;
    }

