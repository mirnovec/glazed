    @EventHandler
    private void onRender(Render3DEvent event) {
        if (mc.player == null || mc.level == null || oreConfig == null) return;

        int maxDist = maxDistance.get();
        double maxSq = (double) maxDist * maxDist;
        ChunkPos playerChunk = mc.player.chunkPosition();
        boolean unloaded = predictUnloaded.get();
        int range = unloaded ? Math.max(chunkRange.get(), unloadedRange.get()) : chunkRange.get();
        boolean fade = unloaded && fadeUnloaded.get();

        // dragging the sliders past each other should not silently hide the whole world
        int lo = Math.min(minY.get(), maxY.get());
        int hi = Math.max(minY.get(), maxY.get());

        boolean drawDiscarded = showDiscarded.get();
        boolean drawTracers = tracers.get();
        boolean onlyNearest = nearestOnly.get();
        int alpha = sideAlpha.get();
        ShapeMode mode = shapeMode.get();

        BlockPos nearest = null;
        OverworldOre.Type nearestType = null;
        double nearestSq = Double.MAX_VALUE;

        for (int cx = playerChunk.x() - range; cx <= playerChunk.x() + range; cx++) {
            for (int cz = playerChunk.z() - range; cz <= playerChunk.z() + range; cz++) {
                long key = ChunkPos.pack(cx, cz);
                List<Vein> veins = results.get(key);
                if (veins == null) continue;

                // nothing in this chunk was checked against a real block, so say so visually
                boolean guessed = fade && rawChunks.contains(key);
                int chunkAlpha = guessed ? Math.max(8, alpha / 3) : alpha;

                for (Vein vein : veins) {
                    if (!enabled(vein.type())) continue;

                    // whole-vein rejects first: exact on Y, radius-padded on distance
                    if (vein.hiY() < lo || vein.loY() > hi) continue;

                    double cull = maxDist + vein.radius();
                    if (mc.player.distanceToSqr(vein.x(), vein.y(), vein.z()) > cull * cull) continue;

                    Color line = colorOf(vein.type());
                    if (guessed) line = new Color(line.r, line.g, line.b, Math.max(60, line.a / 2));
                    Color side = new Color(line.r, line.g, line.b, chunkAlpha);

                    // the tracer has to end on a block that actually got drawn, so pick it while drawing
                    BlockPos target = null;
                    double targetSq = Double.MAX_VALUE;

                    for (BlockPos pos : vein.blocks()) {
                        if (pos.getY() < lo || pos.getY() > hi) continue;
                        if (isMined(pos)) continue;

                        double distSq = distanceSqr(pos);
                        if (distSq > maxSq) continue;

                        event.renderer.box(
                            pos.getX(), pos.getY(), pos.getZ(),
                            pos.getX() + 1, pos.getY() + 1, pos.getZ() + 1,
                            side, line, mode, 0);

                        if (distSq < targetSq) {
                            targetSq = distSq;
                            target = pos;
                        }
                    }

                    if (drawDiscarded) {
                        Color dLine = discardedColor.get();
                        Color dSide = new Color(dLine.r, dLine.g, dLine.b, chunkAlpha);

                        for (BlockPos pos : vein.discarded()) {
                            if (pos.getY() < lo || pos.getY() > hi) continue;
                            if (isMined(pos)) continue;

                            double distSq = distanceSqr(pos);
                            if (distSq > maxSq) continue;

                            event.renderer.box(
                                pos.getX(), pos.getY(), pos.getZ(),
                                pos.getX() + 1, pos.getY() + 1, pos.getZ() + 1,
                                dSide, dLine, mode, 0);

                            if (distSq < targetSq) {
                                targetSq = distSq;
                                target = pos;
                            }
                        }
                    }

                    // nothing of this vein survived the filters, so it gets no tracer either
                    if (target == null || !drawTracers) continue;

                    if (onlyNearest) {
                        if (targetSq < nearestSq) {
                            nearestSq = targetSq;
                            nearest = target;
                            nearestType = vein.type();
                        }
                    } else {
                        tracer(event, target, line);
                    }
                }
            }
        }

        if (drawTracers && onlyNearest && nearest != null) tracer(event, nearest, colorOf(nearestType));
    }

    private double distanceSqr(BlockPos pos) {
        return mc.player.distanceToSqr(pos.getX() + 0.5, pos.getY() + 0.5, pos.getZ() + 0.5);
    }

    private void tracer(Render3DEvent event, BlockPos pos, Color color) {
        event.renderer.line(
            RenderUtils.center.x, RenderUtils.center.y, RenderUtils.center.z,
            pos.getX() + 0.5, pos.getY() + 0.5, pos.getZ() + 0.5,
            color);
    }

