    // Simulation
    // ====================================

    private void compute(ChunkPos pos) {
        if (mc.level == null || oreConfig == null || activeOres == null) return;
        if (PlayerUtils.getDimension() != Dimension.Overworld) return;

        long key = pos.pack();
        // The player may have /rtp'd since this key was queued.
        if (!inActiveRange(key)) return;
        if (results.containsKey(key)) return;

        ChunkAccess chunk = mc.level.getChunk(pos.x(), pos.z(), ChunkStatus.FULL, false);

        // a vein on a chunk edge reads its neighbour's blocks; if that chunk has not arrived
        // yet every lookup answers air and the whole vein is wrongly discarded. Leaving it
        // uncached means the sweep above retries once the neighbours land.
        boolean verified = chunk != null && neighboursLoaded(pos);

        // Hidden emerald is never verified from client blocks: Donut may represent the exact same
        // buried ore as air or deepslate. Wait for the seed-generated terrain even when this
        // source chunk is already loaded, then use that one authoritative path everywhere.
        SeedWorld exactWorld = seedWorld;
        if (enabled(OverworldOre.Type.EMERALD)
            && (exactWorld == null || exactWorld.seed != seed)) return;

        if (!verified) {
            // without blocks the only honest options are predicting from the seed or waiting
            if (!predictUnloaded.get() || seedWorld == null) return;

            SeedWorld world = seedWorld;
            if (world.seed != seed) return;
        }

        try {
            simulate(pos, key, verified);
        } catch (TerrainPending pending) {
            long expectedEpoch = workEpoch;
            SeedWorld expectedWorld = seedWorld;
            if (terrainWaiting.add(key)) {
                pending.future.whenComplete((unused, error) -> {
                    if (workEpoch != expectedEpoch || seedWorld != expectedWorld) return;
                    terrainWaiting.remove(key);
                    terrainReady.add(key);
                });
            }
        } catch (IllegalStateException failure) {
            Throwable terrainFailure = seedWorld == null ? null : seedWorld.terrainFailure();
            if (terrainFailure == null) throw failure;
            if (!terrainFailureReported) {
                terrainFailureReported = true;
                error("Exact emerald terrain failed; unloaded emerald output is disabled: %s", terrainFailure);
            }
        } finally {
            rawPass = false;
        }
    }

    private void simulate(ChunkPos pos, long key, boolean verified) {
        int chunkX = pos.getMinBlockX();
        int chunkZ = pos.getMinBlockZ();

        WorldgenRandom random = new WorldgenRandom(WorldgenRandom.Algorithm.XOROSHIRO.newInstance(0));
        long populationSeed = random.setDecorationSeed(seed, chunkX, chunkZ);

        List<Vein> veins = new ArrayList<>();
        simulationChunk = pos;
        boolean seedBacked = false;

        try {
        for (OverworldOre ore : activeOres) {
            // Emerald always follows the same seed terrain path. Other enabled types may still use
            // truthful loaded blocks for diagnostics, while unloaded chunks remain seed-backed.
            rawPass = !verified || ore.type == OverworldOre.Type.EMERALD;
            if (rawPass) seedBacked = true;

            // every feature in the dimension runs for every chunk, the biome filter is what rejects it
            random.setFeatureSeed(populationSeed, ore.index, ore.step);

            int repeat = ore.count.sample(random);

            for (int i = 0; i < repeat; i++) {
                if (ore.rarity != 1 && random.nextFloat() >= 1.0f / ore.rarity) continue;

                int x = random.nextInt(16) + chunkX;
                int z = random.nextInt(16) + chunkZ;
                int y = ore.heightProvider.sample(random, ore.heightContext);

                BlockPos origin = new BlockPos(x, y, z);

                if (!biomeHas(origin, ore)) continue;

                discardBuffer.clear();

                List<BlockPos> blocks = ore.scattered
                    ? generateScattered(random, origin, ore)
                    : generateNormal(random, origin, ore);

                List<BlockPos> discarded = new ArrayList<>(discardBuffer);

                if (blocks.isEmpty() && discarded.isEmpty()) continue;

                List<BlockPos> centreOf = blocks.isEmpty() ? discarded : blocks;
                double cx = 0, cy = 0, cz = 0;
                for (BlockPos p : centreOf) {
                    cx += p.getX() + 0.5;
                    cy += p.getY() + 0.5;
                    cz += p.getZ() + 0.5;
                }
                cx /= centreOf.size();
                cy /= centreOf.size();
                cz /= centreOf.size();

                int loY = Integer.MAX_VALUE, hiY = Integer.MIN_VALUE;
                double radiusSq = 0;
                for (int list = 0; list < 2; list++) {
                    for (BlockPos p : list == 0 ? blocks : discarded) {
                        loY = Math.min(loY, p.getY());
                        hiY = Math.max(hiY, p.getY());
                        double dx = p.getX() + 0.5 - cx, dy = p.getY() + 0.5 - cy, dz = p.getZ() + 0.5 - cz;
                        radiusSq = Math.max(radiusSq, dx * dx + dy * dy + dz * dz);
                    }
                }

                veins.add(new Vein(ore.type, blocks, discarded, cx, cy, cz, loY, hiY, Math.sqrt(radiusSq)));
            }
        }
        } finally {
            simulationChunk = null;
            buildingPreEmeraldMask = false;
        }

        results.put(key, veins);

        if (seedBacked) rawChunks.add(key);
        else rawChunks.remove(key);
    }

    private boolean neighboursLoaded(ChunkPos pos) {
        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                if (mc.level.getChunk(pos.x() + dx, pos.z() + dz, ChunkStatus.FULL, false) == null) return false;
            }
        }

        return true;
    }

    private boolean biomeHas(BlockPos pos, OverworldOre ore) {
        ResourceKey<Biome> biome;
        try {
            biome = rawPass
                ? seedWorld.biome(pos.getX(), pos.getY(), pos.getZ())
                : mc.level.getBiome(pos).unwrapKey().orElse(null);
        } catch (SeedWorld.GenerationPending pending) {
            throw new TerrainPending(pending.future());
        }

        if (biome == null) return false;

        List<OverworldOre> ores = oreConfig.get(biome);
        return ores != null && ores.contains(ore);
    }

    /**
     * Vanilla's OreFeature gates the whole vein on OCEAN_FLOOR_WG, which the server never sends.
     * MOTION_BLOCKING is sent, and it is the same heightmap plus fluids, so walking down from it
     * past the water column lands on the ocean floor. Close enough underground, which is the only
     * place the answer changes anything.
     */
    private int oceanFloor(int x, int z) {
        if (rawPass) {
            Integer floor = seedWorld.oceanFloor(x, z);
            if (floor == null) {
                throw new TerrainPending(seedWorld.prepareTerrain(new ChunkPos(x >> 4, z >> 4)));
            }
            return floor;
        }

        long key = ChunkPos.pack(x, z);
        Integer cached = floorCache.get(key);
        if (cached != null) return cached;

        int levelMin = mc.level.getMinY();
        int y = mc.level.getHeight(Heightmap.Types.MOTION_BLOCKING, x, z);
        int result = levelMin;

        BlockPos.MutableBlockPos mutable = new BlockPos.MutableBlockPos();

        for (int yy = y; yy > levelMin; yy--) {
            mutable.set(x, yy - 1, z);
            BlockState state = mc.level.getBlockState(mutable);

            if (state.blocksMotion() && state.getFluidState().isEmpty()) {
                result = yy;
                break;
            }
        }

        floorCache.put(key, result);
        return result;
    }

    /**
     * Vanilla's canPlaceOre. The random has to be consumed exactly as vanilla consumes it no
     * matter what the air-check setting says, otherwise the stream drifts and every position
     * after this one is wrong.
     *
     * Raw mode assumes the position was replaceable stone, which burns the discard float exactly
     * once, the same as vanilla does for either stone or deepslate.
     */
    private boolean canPlace(BlockPos pos, OverworldOre ore, WorldgenRandom random) {
        // Deep emerald is rare enough to generate exact noise and carvers for every candidate.
        // Other raw ores retain the old geometry-only behaviour; Em Ore never reads those.
        if (rawPass) {
            if (!forceRaw && (buildingPreEmeraldMask
                || ore.type == OverworldOre.Type.EMERALD && pos.getY() <= 0)) {
                return canPlaceInSeedTerrain(pos, ore, random);
            }

            shouldSkipAirCheck(random, ore.discardOnAirChance);
            return true;
        }

        RngMode mode = rngOverride != null ? rngOverride : rngMode.get();
        boolean filter = !forceRaw && airCheck.get() != AirCheck.Off;

        // AlwaysStone never reads the world to decide the random, so the stream comes out the
        // same however mined out the area is. The other two let the world decide, which is right
        // for a natural cave (carvers run before ores, so vanilla really did skip the float) and
        // wrong for a tunnel somebody dug after the fact.
        if (mode == RngMode.AlwaysStone) {
            boolean skipAir = shouldSkipAirCheck(random, ore.discardOnAirChance);
            return !filter || worldAllows(pos, ore, skipAir);
        }

        BlockState state = mc.level.getBlockState(pos);

        if (state.isAir()) {
            // Donut's anti-xray is allowed to replace a buried ore with air. For emerald that
            // cannot be treated as a natural cave: rejecting it deletes a valid seed candidate
            // and also changes the remainder of OreFeature's random stream. Re-check the
            // unobfuscated seed terrain instead. A genuine vanilla cave was already rejected by
            // this same check during the unloaded pass.
            if (!forceRaw && ore.type == OverworldOre.Type.EMERALD
                && seedWorld != null && seedWorld.seed == seed) {
                return canPlaceInSeedTerrain(pos, ore, random);
            }

            if (mode == RngMode.AirAsStone) shouldSkipAirCheck(random, ore.discardOnAirChance);
            return false;
        }

        // an unmined vein reads back as the ore itself on servers that do not obfuscate. The
        // discard float is still burned so the stream stays lined up with vanilla.
        for (Block block : ore.resultBlocks) {
            if (state.is(block)) {
                shouldSkipAirCheck(random, ore.discardOnAirChance);
                return true;
            }
        }

        for (OreConfiguration.TargetBlockState target : ore.targetStates) {
            if (!target.target.test(state, random)) continue;

            boolean skipAir = shouldSkipAirCheck(random, ore.discardOnAirChance);
            if (!filter) return true;
            return skipAir || !adjacentToAir(pos);
        }

        return false;
    }

    /** Vanilla canPlaceOre evaluated against the seed-generated, post-carver ProtoChunk. */
    private boolean canPlaceInSeedTerrain(BlockPos pos, OverworldOre ore, WorldgenRandom random) {
        SeedWorld world = seedWorld;
        if (world == null || world.seed != seed || world.terrainFailure() != null) {
            throw new IllegalStateException("Seed terrain is unavailable");
        }

        BlockState state = world.terrainBlock(pos);
        if (state == null) throw new TerrainPending(world.prepareTerrain(pos));

        if (!buildingPreEmeraldMask && ore.type == OverworldOre.Type.EMERALD) {
            Set<Long> replaced = preEmeraldMask();
            if (replaced.contains(pos.asLong())) {
                terrainRejected++;
                return false;
            }
        }

        for (OreConfiguration.TargetBlockState target : ore.targetStates) {
            if (!target.target.test(state, random)) continue;

            boolean skipAir = shouldSkipAirCheck(random, ore.discardOnAirChance);
            // This is authoritative vanilla terrain, not the optional client-world display
            // filter. Always consume/apply OreFeature's discard-on-air rule here.
            if (!skipAir && adjacentToSeedAir(pos, world)) {
                if (ore.type == OverworldOre.Type.EMERALD) terrainRejected++;
                return false;
            }

            if (ore.type == OverworldOre.Type.EMERALD) terrainAccepted++;
            return true;
        }

        if (ore.type == OverworldOre.Type.EMERALD) terrainRejected++;
        return false;
    }

    /**
     * Replays every registered feature before emerald (index 33) for the placement chunk and its
     * immediate neighbours. Their union is enough: whichever earlier feature wins, the block is
     * no longer stone/deepslate when emerald runs.
     */
    private Set<Long> preEmeraldMask() {
        ChunkPos centre = simulationChunk;
        if (centre == null) return Set.of();

        long cacheKey = centre.pack();
        Set<Long> cached = preEmeraldMasks.get(cacheKey);
        if (cached != null) return cached;

        List<BlockPos> savedDiscarded = new ArrayList<>(discardBuffer);
        Set<Long> replaced = new HashSet<>();
        buildingPreEmeraldMask = true;

        try {
            List<OverworldOre> earlier = OverworldOre.all().stream()
                .filter(ore -> ore.index < 33 && ore.heightProvider != null)
                .sorted(java.util.Comparator.comparingInt(ore -> ore.index))
                .toList();

            for (int dx = -1; dx <= 1; dx++) {
                for (int dz = -1; dz <= 1; dz++) {
                    ChunkPos originChunk = new ChunkPos(centre.x() + dx, centre.z() + dz);
                    int chunkX = originChunk.getMinBlockX();
                    int chunkZ = originChunk.getMinBlockZ();
                    WorldgenRandom priorRandom = new WorldgenRandom(WorldgenRandom.Algorithm.XOROSHIRO.newInstance(0));
                    long populationSeed = priorRandom.setDecorationSeed(seed, chunkX, chunkZ);

                    for (OverworldOre prior : earlier) {
                        priorRandom.setFeatureSeed(populationSeed, prior.index, prior.step);
                        int repeat = prior.count.sample(priorRandom);

                        for (int attempt = 0; attempt < repeat; attempt++) {
                            if (prior.rarity != 1 && priorRandom.nextFloat() >= 1.0f / prior.rarity) continue;

                            int x = priorRandom.nextInt(16) + chunkX;
                            int z = priorRandom.nextInt(16) + chunkZ;
                            int y = prior.heightProvider.sample(priorRandom, prior.heightContext);
                            // An emerald block at y<=0 cannot overlap a vein whose origin is this
                            // far above it, even for the largest registered underground feature.
                            if (y > 16) continue;
                            BlockPos origin = new BlockPos(x, y, z);
                            if (!biomeHas(origin, prior)) continue;

                            discardBuffer.clear();
                            List<BlockPos> blocks = prior.scattered
                                ? generateScattered(priorRandom, origin, prior)
                                : generateNormal(priorRandom, origin, prior);
                            int minX = centre.getMinBlockX() - 4;
                            int maxX = centre.getMaxBlockX() + 4;
                            int minZ = centre.getMinBlockZ() - 4;
                            int maxZ = centre.getMaxBlockZ() + 4;
                            for (BlockPos block : blocks) {
                                if (block.getX() >= minX && block.getX() <= maxX
                                    && block.getZ() >= minZ && block.getZ() <= maxZ) {
                                    replaced.add(block.asLong());
                                }
                            }
                        }
                    }
                }
            }

            Set<Long> result = Set.copyOf(replaced);
            preEmeraldMasks.put(cacheKey, result);
            return result;
        } finally {
            buildingPreEmeraldMask = false;
            discardBuffer.clear();
            discardBuffer.addAll(savedDiscarded);
        }
    }

    private boolean adjacentToSeedAir(BlockPos pos, SeedWorld world) {
        for (Direction direction : Direction.values()) {
            BlockPos adjacent = pos.relative(direction);
            BlockState state = world.terrainBlock(adjacent);
            if (state == null) throw new TerrainPending(world.prepareTerrain(adjacent));
            if (state.isAir()) return true;
        }

        return false;
    }

    /** Display filter only. Uses its own random so it can never move the worldgen stream. */
    private boolean worldAllows(BlockPos pos, OverworldOre ore, boolean skipAir) {
        BlockState state = mc.level.getBlockState(pos);
        if (state.isAir()) return false;

        for (Block block : ore.resultBlocks) {
            if (state.is(block)) return true;
        }

        for (OreConfiguration.TargetBlockState target : ore.targetStates) {
            if (!target.target.test(state, filterRandom)) continue;
            return skipAir || !adjacentToAir(pos);
        }

        return false;
    }

    private boolean shouldSkipAirCheck(WorldgenRandom random, float discardOnAir) {
        if (discardOnAir <= 0f) return true;
        if (discardOnAir >= 1f) return false;
        return random.nextFloat() >= discardOnAir;
    }

    /** Vanilla tests BlockState.isAir(), not canOcclude, so lava and slabs are not exposure. */
    private boolean adjacentToAir(BlockPos pos) {
        for (Direction dir : Direction.values()) {
            if (mc.level.getBlockState(pos.relative(dir)).isAir()) return true;
        }

        return false;
    }

    // Mojang's OreFeature, kept in its original shape so it stays easy to diff against vanilla
    private List<BlockPos> generateNormal(WorldgenRandom random, BlockPos blockPos, OverworldOre ore) {
        int veinSize = ore.size;

        float f = random.nextFloat() * Mth.PI;
        float g = (float) veinSize / 8.0F;
        int i = Mth.ceil(((float) veinSize / 16.0F * 2.0F + 1.0F) / 2.0F);
        double d = (double) blockPos.getX() + Math.sin(f) * (double) g;
        double e = (double) blockPos.getX() - Math.sin(f) * (double) g;
        double h = (double) blockPos.getZ() + Math.cos(f) * (double) g;
        double j = (double) blockPos.getZ() - Math.cos(f) * (double) g;
        double l = blockPos.getY() + random.nextInt(3) - 2;
        double m = blockPos.getY() + random.nextInt(3) - 2;
        int n = blockPos.getX() - Mth.ceil(g) - i;
        int o = blockPos.getY() - 2 - i;
        int p = blockPos.getZ() - Mth.ceil(g) - i;
        int q = 2 * (Mth.ceil(g) + i);
        int r = 2 * (2 + i);

        // nothing in the overworld has terrain this low, so a deep vein clears the gate without
        // making the seed world sample a single noise column. Every deepslate ore takes this path.
        if (rawPass && o <= SeedWorld.ALWAYS_UNDERGROUND) {
            return generateVeinPart(random, ore, d, e, h, j, l, m, n, o, p, q, r);
        }

        for (int s = n; s <= n + q; ++s) {
            for (int t = p; t <= p + q; ++t) {
                if (o <= oceanFloor(s, t)) {
                    return generateVeinPart(random, ore, d, e, h, j, l, m, n, o, p, q, r);
                }
            }
        }

        return new ArrayList<>();
    }

    private List<BlockPos> generateVeinPart(
        WorldgenRandom random, OverworldOre ore,
        double startX, double endX, double startZ, double endZ, double startY, double endY,
        int x, int y, int z, int size, int i
    ) {
        int veinSize = ore.size;

        BitSet bitSet = new BitSet(size * i * size);
        BlockPos.MutableBlockPos mutable = new BlockPos.MutableBlockPos();
        double[] ds = new double[veinSize * 4];

        List<BlockPos> poses = new ArrayList<>();

        int n;
        double p;
        double q;
        double r;
        double s;

        for (n = 0; n < veinSize; ++n) {
            float f = (float) n / (float) veinSize;
            p = Mth.lerp(f, startX, endX);
            q = Mth.lerp(f, startY, endY);
            r = Mth.lerp(f, startZ, endZ);
            s = random.nextDouble() * (double) veinSize / 16.0D;
            double m = ((double) (Mth.sin(Mth.PI * f) + 1.0F) * s + 1.0D) / 2.0D;
            ds[n * 4] = p;
            ds[n * 4 + 1] = q;
            ds[n * 4 + 2] = r;
            ds[n * 4 + 3] = m;
        }

        for (n = 0; n < veinSize - 1; ++n) {
            if (!(ds[n * 4 + 3] <= 0.0D)) {
                for (int o = n + 1; o < veinSize; ++o) {
                    if (!(ds[o * 4 + 3] <= 0.0D)) {
                        p = ds[n * 4] - ds[o * 4];
                        q = ds[n * 4 + 1] - ds[o * 4 + 1];
                        r = ds[n * 4 + 2] - ds[o * 4 + 2];
                        s = ds[n * 4 + 3] - ds[o * 4 + 3];
                        if (s * s > p * p + q * q + r * r) {
                            if (s > 0.0D) ds[o * 4 + 3] = -1.0D;
                            else ds[n * 4 + 3] = -1.0D;
                        }
                    }
                }
            }
        }

        for (n = 0; n < veinSize; ++n) {
            double u = ds[n * 4 + 3];
            if (u < 0.0D) continue;

            double v = ds[n * 4];
            double w = ds[n * 4 + 1];
            double aa = ds[n * 4 + 2];
            int ab = Math.max(Mth.floor(v - u), x);
            int ac = Math.max(Mth.floor(w - u), y);
            int ad = Math.max(Mth.floor(aa - u), z);
            int ae = Math.max(Mth.floor(v + u), ab);
            int af = Math.max(Mth.floor(w + u), ac);
            int ag = Math.max(Mth.floor(aa + u), ad);

            for (int ah = ab; ah <= ae; ++ah) {
                double ai = ((double) ah + 0.5D - v) / u;
                if (ai * ai >= 1.0D) continue;

                for (int aj = ac; aj <= af; ++aj) {
                    double ak = ((double) aj + 0.5D - w) / u;
                    if (ai * ai + ak * ak >= 1.0D) continue;

                    for (int al = ad; al <= ag; ++al) {
                        double am = ((double) al + 0.5D - aa) / u;
                        if (ai * ai + ak * ak + am * am >= 1.0D) continue;

                        if (mc.level.isOutsideBuildHeight(aj)) continue;

                        int an = ah - x + (aj - y) * size + (al - z) * size * i;
                        if (bitSet.get(an)) continue;
                        bitSet.set(an);

                        mutable.set(ah, aj, al);

                        if (canPlace(mutable, ore, random)) poses.add(mutable.immutable());
                        else discardBuffer.add(mutable.immutable());
                    }
                }
            }
        }

        return poses;
    }

    /** Nothing in the overworld takes this path, it is here so a ported feature cannot silently break. */
    private List<BlockPos> generateScattered(WorldgenRandom random, BlockPos blockPos, OverworldOre ore) {
        List<BlockPos> poses = new ArrayList<>();

        int i = random.nextInt(ore.size + 1);

        for (int j = 0; j < i; ++j) {
            int spread = Math.min(j, 7);
            int x = randomCoord(random, spread) + blockPos.getX();
            int y = randomCoord(random, spread) + blockPos.getY();
            int z = randomCoord(random, spread) + blockPos.getZ();

            BlockPos pos = new BlockPos(x, y, z);

            if (canPlace(pos, ore, random)) poses.add(pos);
            else discardBuffer.add(pos);
        }

        return poses;
    }

    private int randomCoord(WorldgenRandom random, int size) {
        return Math.round((random.nextFloat() - random.nextFloat()) * (float) size);
    }

