    /** True when the block came out of the seed alone and was never checked against real blocks. */
    public boolean isGuess(BlockPos pos) {
        if (pos == null) return false;
        ChunkPos blockChunk = ChunkPos.containing(pos);

        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                long sourceKey = ChunkPos.pack(blockChunk.x() + dx, blockChunk.z() + dz);
                if (!rawChunks.contains(sourceKey)) continue;
                List<Vein> veins = results.get(sourceKey);
                if (veins == null) continue;
                for (Vein vein : veins) if (vein.blocks().contains(pos)) return true;
            }
        }

        return false;
    }

